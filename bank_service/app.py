
import re
import uuid
from decimal import Decimal, InvalidOperation
from pathlib import Path

import requests
from requests.exceptions import RequestException

from flask import Flask, jsonify, request, send_from_directory
from cryptography.hazmat.primitives import serialization

from crypto.ecdsa_sign import (
    sign_transaction,
    export_public_key
)


BASE_DIR = Path(__file__).resolve().parent.parent
FRONTEND_DIR = BASE_DIR / "frontend"
PRIVATE_KEY_PATH = BASE_DIR / "keys" / "bank_private.pem"

TRANSACTION_SERVER_URL = "http://127.0.0.1:5001/api/transactions"

app = Flask(__name__, static_folder=None)


# Load the persistent ECDSA private key.
# This key was generated by crypto/generate_keys.py.
# It must NOT be regenerated for each transaction.
with open(PRIVATE_KEY_PATH, "rb") as key_file:
    private_key = serialization.load_pem_private_key(
        key_file.read(),
        password=None
    )

public_key = private_key.public_key()


# Temporary website history.
# Actual completed transactions are stored in PostgreSQL.
# We will replace this with database-backed history later.
pending_transfers = []

ALLOWED_RECEIVERS = {"ALICE", "BOB"}


def validate_transfer(data):
    if not isinstance(data, dict):
        return None, "Expected a JSON object"

    receiver = data.get("receiver")
    amount = data.get("amount")
    currency = data.get("currency")

    if receiver not in ALLOWED_RECEIVERS:
        return None, "Invalid receiver"

    if currency != "EUR":
        return None, "Only EUR is supported"

    if not isinstance(amount, str):
        return None, "Amount must be a decimal string"

    if not re.fullmatch(r"\d{1,10}\.\d{2}", amount):
        return None, "Amount must use format 100.00"

    try:
        value = Decimal(amount)
    except InvalidOperation:
        return None, "Invalid amount"

    if value <= 0:
        return None, "Amount must be positive"

    transaction = {
        "transaction_id": f"TX-{uuid.uuid4().hex[:12].upper()}",
        "sender": "BANK",
        "receiver": receiver,
        "amount": amount,
        "currency": currency
    }

    return transaction, None


